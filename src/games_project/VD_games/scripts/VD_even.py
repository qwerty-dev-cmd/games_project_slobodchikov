"""Игра: Проверка на чётность."""
# Это docstring — документация к модулю. Описывает, что делает этот файл.
# Хороший тон программирования — всегда описывать назначение модуля.

import random  # Импортируем модуль для генерации случайных чисел
import prompt  # Импортируем библиотеку для красивого ввода от пользователя


def is_even(number):
    """
    Проверяет, является ли число чётным.
    
    Параметры:
        number (int): число для проверки
        
    Возвращает:
        bool: True если число чётное, False если нечётное
    """
    # Оператор % возвращает остаток от деления
    # Если остаток от деления на 2 равен 0, значит число чётное
    return number % 2 == 0


def run_game():
    """
    Запускает игру 'Проверка на чётность'.
    
    Эта функция содержит основную логику игры:
    1. Приветствие и знакомство
    2. Три раунда с вопросами
    3. Проверка ответов
    4. Вывод результата (победа или поражение)
    """
    # Выводим приветствие
    print("Welcome to the VD-games!")
    
    # Запрашиваем имя пользователя с помощью библиотеки prompt
    # prompt.string() сам повторяет запрос, если пользователь ничего не ввёл
    name = prompt.string("May I have your name? ")
    
    # Приветствуем пользователя по имени (f-строка подставляет значение переменной)
    print(f"Hello, {name}!")
    
    # Объясняем правила игры
    print('Answer "yes" if the number is even, otherwise answer "no".')

    # Счётчик правильных ответов
    correct_answers = 0
    
    # Количество раундов для победы
    rounds_to_win = 3

    # Основной игровой цикл
    # Играем пока не наберём нужное количество правильных ответов
    while correct_answers < rounds_to_win:
        # Генерируем случайное число от 1 до 100
        number = random.randint(1, 100)
        
        # Показываем вопрос пользователю
        print(f"Question: {number}")
        
        # Получаем ответ пользователя
        # .strip() удаляет лишние пробелы в начале и конце
        # .lower() приводит ответ к нижнему регистру (чтобы "YES" и "yes" считались одинаково)
        answer = prompt.string("Your answer: ").strip().lower()

        # Определяем правильный ответ для текущего числа
        # Если число чётное - правильный ответ "yes", иначе "no"
        correct_answer = "yes" if is_even(number) else "no"

        # Сравниваем ответ пользователя с правильным
        if answer == correct_answer:
            # Если ответ правильный
            print("Correct!")
            # Увеличиваем счётчик правильных ответов
            correct_answers += 1
        else:
            # Если ответ неправильный
            # Выводим сообщение об ошибке
            print(f"'{answer}' is wrong answer ;(. Correct answer was '{correct_answer}'.")
            # Предлагаем попробовать снова
            print(f"Let's try again, {name}!")
            # Завершаем игру (выходим из функции)
            return

    # Если мы вышли из цикла (набрали 3 правильных ответа)
    # Поздравляем пользователя с победой
    print(f"Congratulations, {name}!")


def main():
    """
    Основная функция - точка входа в игру.
    Просто вызывает run_game().
    """
    run_game()


# Эта конструкция гарантирует, что код выполнится только при прямом запуске файла
# Если файл импортируется как модуль в другом файле, код под if не выполнится
if __name__ == "__main__":
    main()
